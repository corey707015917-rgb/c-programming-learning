#include <stdio.h>

//======================================================
//第一部分：定义结构体类型 struct
//======================================================
struct DeviceStatus
{
    //id:结构体中的一个成员，保存设备编号。
    int id;

    float temperature;

    // is_on: 保存设备的开关状态
    //约定1代表开启，0代表关闭
    int is_on;
};
//注意：结构体定义结束后需要写分号；
//到这里，我们只是定义了一种数据类型
//还没有创建任何具体的设备变量


//======================================================
//第二部分：主函数main()
//======================================================

//int: 表示main函数返回一个整数
//main 程序的入口函数
//void 表示main函数不接受参数
int main(void)
{
    //======================================================
    //1.创建一台设备
    //======================================================

    //struct DeviceStatus：变量的数据类型。
    //device：变量名称，代表一台具体设备。

    // {1, 25.5f, 1}：初始化列表。
    // 这些值按照结构体成员的定义顺序依次赋值。

    // 第一个 1    → device.id = 1
    // 第二个 25.5f → device.temperature = 25.5
    // 第三个 1    → device.is_on = 1
    //
    // 25.5f 中的 f 表示这是 float 类型的浮点常量。
    // 如果写成 25.5，默认是 double 类型。
    //
    // 最后的分号 ; 表示语句结束。
    struct DeviceStatus device = {1, 25.5f, 1};

    //======================================================
    //2.输出设备编号
    //======================================================

    //device.id 表示读取这台设备的编号。

    printf("Device ID: %d\n",device.id);

    //======================================================
    //3.输出设备温度
    //======================================================

    //device.temperature：
    //访问 device 结构体中的 temperature 成员。

    printf("Temperature: %.1f C\n", device.temperature);
    //上面的C表示的是摄氏度

    //======================================================
    //4.输出设备开关状态
    //======================================================

    
    
    //以上这一行使用了三元条件运算符 ？ ：
    //
    //先单独看：
    //device.is_on ? "ON" : "OFF"
    //
    //它的结构是：
    //条件 ？ 条件为真时选择的值 ： 条件为假时选择的值
    //
    //第一步：
    //读取 device.is_on
    //当前 device.is_on = 1。
    //
    //第二步：
    //判断这个值是真是假
    //在C语言中，0表示假，非0表示真
    //因此这里的1表示真
    //
    //第三步：
    //条件为真，选择字符串“ON”
    //如果 is_on = 0 就选择 “OFF”
    //
    //%s 表示以字符串格式输出

    printf("Status: %s\n", device.is_on ? "ON" : "OFF");

    //======================================================
    //5.结束程序
    //======================================================
    return 0;



}